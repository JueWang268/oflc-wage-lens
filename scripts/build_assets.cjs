const fs = require('node:fs');
const path = require('node:path');
const runtime = process.env.WAGE_LENS_NODE_MODULES;
const from = name => require(runtime ? path.join(runtime, name) : name);
const lucide = from('lucide/dist/cjs/lucide.js');
const sharp = from('sharp');
const base = path.join(__dirname, '..', 'extension');
const names = ['ChartNoAxesColumnIncreasing', 'RefreshCw', 'Minus', 'X', 'ChevronDown', 'ArrowDown', 'ArrowLeft', 'ArrowRight'];
const icons = Object.fromEntries(names.map(name => [name, lucide[name]]));
fs.writeFileSync(path.join(base, 'icons.js'), '/* Icons: Lucide, ISC license. Generated by scripts/build_assets.cjs. */\nglobalThis.WageLensAssets = ' + JSON.stringify({icons, css: fs.readFileSync(path.join(base, 'panel.css'), 'utf8')}) + ';\n');
const nodes = icons.ChartNoAxesColumnIncreasing.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k,v])=>`${k}="${v}"`).join(' ')}/>`).join('');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="6" fill="#176b4b"/><g transform="translate(4 4)" stroke="white" fill="none" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${nodes}</g></svg>`;
fs.mkdirSync(path.join(base, 'icons'), {recursive:true});
Promise.all([48,96].map(size => sharp(Buffer.from(svg)).resize(size,size).png().toFile(path.join(base, 'icons', `icon-${size}.png`)))).then(() => console.log('Built local Lucide icons and panel styles.'));
